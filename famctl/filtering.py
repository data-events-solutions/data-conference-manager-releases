"""Internet pause and website blocking.

* Paused devices: nftables drops everything they forward to the internet.
* Global blocklist: dnsmasq answers 0.0.0.0 for those domains (whole house).
* Per-device blocklist: dnsmasq puts the resolved IPs of those domains into an
  nftables set (needs dnsmasq >= 2.87 with nftset support), and traffic from
  that device's MAC to the set is dropped.
* force_dns: every DNS query on the LAN is redirected to the router, so a phone
  can't skip the blocking by setting 8.8.8.8 manually.
"""

import os


def _set_name(mac):
    return "blk_" + mac.replace(":", "")


def build_nft(devices, router_ip, force_dns):
    """devices: {mac: settings}. Returns an nft script that recreates table inet famctl."""
    lines = ["table inet famctl {"]
    blocked = {mac: d for mac, d in devices.items() if d.get("blocked")}
    for mac in blocked:
        for fam, typ in (("4", "ipv4_addr"), ("6", "ipv6_addr")):
            lines += [f"  set {_set_name(mac)}_v{fam} {{ type {typ}; flags timeout; timeout 1h; }}"]

    lines += ["  chain forward {", "    type filter hook forward priority -10; policy accept;"]
    for mac, dev in sorted(devices.items()):
        if dev.get("paused"):
            lines.append(f"    ether saddr {mac} drop")
    for mac in blocked:
        name = _set_name(mac)
        lines.append(f"    ether saddr {mac} ip daddr @{name}_v4 reject")
        lines.append(f"    ether saddr {mac} ip6 daddr @{name}_v6 reject")
    # Block DNS-over-TLS so phones' "Private DNS" can't bypass the router's DNS.
    if force_dns:
        lines.append("    tcp dport 853 reject")
    lines.append("  }")

    if force_dns:
        lines += [
            "  chain dns_redirect {",
            "    type nat hook prerouting priority -100; policy accept;",
            f"    ip daddr != {router_ip} udp dport 53 dnat ip to {router_ip}",
            f"    ip daddr != {router_ip} tcp dport 53 dnat ip to {router_ip}",
            "  }",
        ]
    lines.append("}")
    return "\n".join(lines) + "\n"


def build_dnsmasq(devices, global_blocked):
    lines = ["# Generated by famctl - do not edit by hand"]
    for domain in sorted(global_blocked):
        lines.append(f"address=/{domain}/0.0.0.0")
        lines.append(f"address=/{domain}/::")
    per_domain = {}
    for mac, dev in devices.items():
        for domain in dev.get("blocked", []):
            per_domain.setdefault(domain, []).append(mac)
    for domain, macs in sorted(per_domain.items()):
        sets = ",".join(
            f"4#inet#famctl#{_set_name(m)}_v4,6#inet#famctl#{_set_name(m)}_v6" for m in sorted(macs)
        )
        lines.append(f"nftset=/{domain}/{sets}")
    return "\n".join(lines) + "\n"


def apply(runner, cfg, devices, global_blocked):
    runner.run("nft delete table inet famctl", check=False)
    runner.run(["nft", "-f", "-"], input_text=build_nft(devices, cfg.router_ip, cfg.force_dns))

    conf = build_dnsmasq(devices, global_blocked)
    if not cfg.dry_run:
        os.makedirs(os.path.dirname(cfg.dnsmasq_conf), exist_ok=True)
        with open(cfg.dnsmasq_conf, "w") as f:
            f.write(conf)
    runner.run(cfg.dnsmasq_restart)
    return conf
